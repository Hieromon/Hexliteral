import * as vscode from 'vscode';
import * as path from 'path';
import * as zlib from 'zlib';
import { DEFAULT_FORMAT_OPTIONS, HexliteralFormatOptions, ManifestSchema } from './config';

/**
 * Retrieves the global format rules from the workspace's hexliteral.json.
 * If the file does not exist, is invalid, or cannot be parsed, it safely falls back to the default options.
 * @param workspaceFolder The current VS Code workspace folder associated with the target file.
 * @returns A promise resolving to the HexliteralFormatOptions to be applied.
 */
async function getGlobalFormatOptions(workspaceFolder: vscode.WorkspaceFolder | undefined): Promise<HexliteralFormatOptions> {
  // Fallback immediately if no workspace is opened (e.g., editing a loose file)
  if (!workspaceFolder) return DEFAULT_FORMAT_OPTIONS;
  
  const manifestUri = vscode.Uri.joinPath(workspaceFolder.uri, 'hexliteral.json');
  try {
    const data = await vscode.workspace.fs.readFile(manifestUri);
    const manifest: ManifestSchema = JSON.parse(Buffer.from(data).toString('utf8'));
    
    // Merge parsed properties with safe defaults to handle partial manifest definitions
    return {
      outputBoundary: manifest.outputBoundary ?? DEFAULT_FORMAT_OPTIONS.outputBoundary,
      cppDeclare: manifest.cppDeclare ?? DEFAULT_FORMAT_OPTIONS.cppDeclare,
      emitSizeMacro: manifest.emitSizeMacro ?? DEFAULT_FORMAT_OPTIONS.emitSizeMacro,
      indentSpaces: manifest.indentSpaces ?? DEFAULT_FORMAT_OPTIONS.indentSpaces,
      headerComment: manifest.headerComment ?? DEFAULT_FORMAT_OPTIONS.headerComment
    };
  } catch {
    // Out-of-the-box fallback: Ignore file not found or JSON parse errors and use hardcoded defaults
    return DEFAULT_FORMAT_OPTIONS;
  }
}

/**
 * Core function for ad-hoc, single-file conversion (e.g., via QuickPick or context menu).
 * Processes the file completely in-memory to ensure maximum performance.
 * @param fileUri The URI of the source file to convert.
 * @param keepGzip If true, saves the intermediate raw .gz binary to the filesystem alongside the header.
 */
export async function convertSingleFile(fileUri: vscode.Uri, keepGzip: boolean = false): Promise<void> {
  const workspaceFolder = vscode.workspace.getWorkspaceFolder(fileUri);
  const options = await getGlobalFormatOptions(workspaceFolder);

  // Read the source file and compress it directly in memory
  const sourceData = await vscode.workspace.fs.readFile(fileUri);
  const gzipped = zlib.gzipSync(sourceData);

  const fileName = path.basename(fileUri.fsPath);
  // Sanitize the file name to generate a valid C++ variable name (e.g., "index.html" -> "index_html")
  const varName = fileName.replace(/[^a-zA-Z0-9_]/g, '_'); 
  
  let cppContent = '';

  // 1. Emit Header Comment (Optional)
  if (options.headerComment) {
    cppContent += `/**\n * Auto-generated by Hexliteral\n * Source: ${fileName}\n */\n\n`;
  }

  cppContent += `// File: ${fileName}, Size: ${gzipped.length}\n`;

  // 2. Emit Size Macro (Optional)
  if (options.emitSizeMacro) {
    cppContent += `#define ${varName}_len ${gzipped.length}\n`;
  }

  // 3. Emit C++ Declaration (Optional)
  if (options.cppDeclare) {
    cppContent += `const uint8_t ${varName}[] = {\n`;
  }

  // 4. Format as Hex Array
  // Pre-allocate and map the compressed buffer to a padded hex string array
  const hexArray: string[] = [];
  for (let i = 0; i < gzipped.length; i++) {
    hexArray.push(`0x${gzipped[i].toString(16).padStart(2, '0')}`);
  }

  // Chunk the hex array into lines based on the output boundary and apply dynamic indentation
  const lines: string[] = [];
  const indent = ' '.repeat(options.indentSpaces);
  for (let i = 0; i < hexArray.length; i += options.outputBoundary) {
    lines.push(indent + hexArray.slice(i, i + options.outputBoundary).join(', '));
  }

  cppContent += lines.join(',\n');

  // 5. Close Declaration
  if (options.cppDeclare) {
    cppContent += '\n};\n';
  } else {
    cppContent += '\n'; // Ensure a trailing newline for naked arrays
  }

  // 6. Write out the generated C++ header file
  const outUri = vscode.Uri.file(fileUri.fsPath + '.gz.h');
  await vscode.workspace.fs.writeFile(outUri, Buffer.from(cppContent, 'utf8'));

  // 7. Optionally write out the raw Gzip binary
  if (keepGzip) {
    const gzipUri = vscode.Uri.file(fileUri.fsPath + '.gz');
    await vscode.workspace.fs.writeFile(gzipUri, gzipped);
  }

  vscode.window.showInformationMessage(`Hexliteral: Converted ${fileName} successfully.`);
}
