import * as vscode from 'vscode';
import * as zlib from 'zlib';
import { DEFAULT_FORMAT_OPTIONS, ManifestSchema, HexliteralFormatOptions } from './config';

/**
 * Core function for orchestrating batch builds driven by hexliteral.json.
 * Iterates through defined builds, applies settings cascade, and aggregates multiple assets into header files.
 * @param workspaceRoot The URI of the workspace root where hexliteral.json is located.
 */
export async function buildFromManifest(workspaceRoot: vscode.Uri): Promise<void> {
  const manifestUri = vscode.Uri.joinPath(workspaceRoot, 'hexliteral.json');

  let manifest: ManifestSchema;
  try {
    const data = await vscode.workspace.fs.readFile(manifestUri);
    manifest = JSON.parse(Buffer.from(data).toString('utf8'));
  } catch (err) {
    vscode.window.showErrorMessage('Hexliteral: hexliteral.json not found or invalid in workspace root.');
    return;
  }

  if (!manifest.builds || manifest.builds.length === 0) {
    vscode.window.showInformationMessage('Hexliteral: No builds defined in hexliteral.json.');
    return;
  }

  // Establish the global baseline format rules for this project
  const globalOptions: HexliteralFormatOptions = {
    outputBoundary: manifest.outputBoundary ?? DEFAULT_FORMAT_OPTIONS.outputBoundary,
    cppDeclare: manifest.cppDeclare ?? DEFAULT_FORMAT_OPTIONS.cppDeclare,
    emitSizeMacro: manifest.emitSizeMacro ?? DEFAULT_FORMAT_OPTIONS.emitSizeMacro,
    indentSpaces: manifest.indentSpaces ?? DEFAULT_FORMAT_OPTIONS.indentSpaces,
    headerComment: manifest.headerComment ?? DEFAULT_FORMAT_OPTIONS.headerComment
  };

  // Process each build task defined in the manifest
  for (const build of manifest.builds) {
    let cppContent = '';

    // -- Header Comment --
    if (globalOptions.headerComment) {
      cppContent += `/**\n * Auto-generated by Hexliteral\n */\n\n`;
    }

    // -- Setup Header Scaffolding (Include Guard, Includes, Namespaces) --
    if (build.guard) {
      cppContent += `#ifndef ${build.guard}\n#define ${build.guard}\n\n`;
    }

    if (build.includes) {
      build.includes.forEach(inc => cppContent += `#include ${inc}\n`);
      cppContent += '\n';
    }
    
    if (build.using) {
      build.using.forEach(ns => cppContent += `using namespace ${ns};\n`);
      cppContent += '\n';
    }

    // Generate dynamic indentation string based on config
    const indent = ' '.repeat(globalOptions.indentSpaces);

    // -- Process Assets --
    for (const item of build.items) {
      const srcUri = vscode.Uri.joinPath(workspaceRoot, item.src);
      let sourceData: Uint8Array;
      
      try {
        sourceData = await vscode.workspace.fs.readFile(srcUri);
      } catch (err) {
        vscode.window.showWarningMessage(`Hexliteral: Source file not found: ${item.src}`);
        continue; // Skip missing files to allow the rest of the build to complete
      }

      const gzipped = zlib.gzipSync(sourceData);

      // Wrap asset in conditional compile macro if defined
      if (item.macro) cppContent += `#if defined(${item.macro})\n`;

      cppContent += `// File: ${item.src}, Size: ${gzipped.length}\n`;

      // Setup Cascade: Asset-level settings override global baseline
      const emitSize = item.emitSizeMacro ?? globalOptions.emitSizeMacro;
      
      // Resolve macro suffix by stripping C++ scope operators (e.g., "WebUI::IndexHtml" -> "IndexHtml")
      const varSuffix = item.var.split('::').pop() || item.var;

      if (emitSize) {
        cppContent += `#define ${varSuffix}_len ${gzipped.length}\n`;
      }

      if (globalOptions.cppDeclare) {
        cppContent += `const uint8_t ${item.var}[] = {\n`;
      }

      // In-memory hex generation and chunking
      const hexArray: string[] = [];
      for (let i = 0; i < gzipped.length; i++) {
        hexArray.push(`0x${gzipped[i].toString(16).padStart(2, '0')}`);
      }

      const lines: string[] = [];
      for (let i = 0; i < hexArray.length; i += globalOptions.outputBoundary) {
        lines.push(indent + hexArray.slice(i, i + globalOptions.outputBoundary).join(', '));
      }

      cppContent += lines.join(',\n');

      if (globalOptions.cppDeclare) {
        cppContent += '\n};\n';
      } else {
        cppContent += '\n';
      }

      if (item.macro) cppContent += `#endif // ${item.macro}\n`;
      cppContent += '\n'; // Add spacing between assets
    }

    // -- Finalize Header --
    if (build.guard) {
      cppContent += `#endif // ${build.guard}\n`;
    }

    const outUri = vscode.Uri.joinPath(workspaceRoot, build.out);
    
    // Handle backup generation if requested and the output file already exists
    if (build.backup) {
      try {
        const stat = await vscode.workspace.fs.stat(outUri);
        if (stat) {
          const backupUri = vscode.Uri.file(outUri.fsPath + '~');
          await vscode.workspace.fs.copy(outUri, backupUri, { overwrite: true });
        }
      } catch {
        // File does not exist yet; safely proceed without backing up
      }
    }
    
    await vscode.workspace.fs.writeFile(outUri, Buffer.from(cppContent, 'utf8'));
  }

  vscode.window.showInformationMessage('Hexliteral: Build from manifest completed successfully.');
}
